package com.wordhold.app.core.words

import android.content.res.AssetManager
import org.json.JSONArray
import org.json.JSONObject

/**
 * The bundled vocabulary shared by the word games.
 *
 * [words] is the curated list puzzles are drawn from. [isWord] also accepts the extra
 * anagrams shipped alongside it, so a game can accept any real answer rather than only
 * the one it had in mind ("slate" as well as "stale").
 */
class WordList(
    val words: List<String>,
    alsoAccepted: Collection<String> = emptyList(),
) {
    private val valid: Set<String> = HashSet(words).apply { addAll(alsoAccepted) }

    fun isWord(candidate: String): Boolean = candidate.lowercase() in valid

    fun wordsOfLength(lengths: IntRange): List<String> = words.filter { it.length in lengths }
}

/**
 * Everything the games read from bundled assets, each parsed once on first use.
 * A game's registry entry picks what it needs from here.
 */
class GameAssets(private val assets: AssetManager) {
    /** `assets/words.json`, generated by `tools/make_words.py`. */
    val words: WordList by lazy {
        val json = readJson("words.json")
        WordList(
            words = json.getJSONArray("words").toStrings(),
            alsoAccepted = json.getJSONArray("alsoAccepted").toStrings(),
        )
    }

    /** Crossword answers and their clues: `assets/crossword.json`, from `tools/make_crossword.py`. */
    val crosswordClues: Map<String, String> by lazy {
        val clues = readJson("crossword.json").getJSONObject("clues")
        clues.keys().asSequence().associateWith { clues.getString(it) }
    }

    private fun readJson(name: String) = JSONObject(assets.open(name).bufferedReader().use { it.readText() })

    private fun JSONArray.toStrings(): List<String> = List(length()) { getString(it) }
}
